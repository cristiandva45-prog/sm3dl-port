/* Shaders del rasterizador (incluido por raster_gl.c; agente R, tanda nocturna 9-10 oct).
 *
 * UN solo fragment shader ("uber") para todos los dibujos: el estado de la etapa de fragmentos se lee de los
 * registros PICA en cada dibujo y entra por uniforms. Semantica tomada de la lectura de Azahar
 * (renderer_software/sw_rasterizer.cpp, sw_texturing.cpp, sw_lighting.cpp; nada copiado literal) y, para el TEV,
 * de tools/tev_ref.py (agente G), que es la referencia del verificador:
 *  - TEV de 6 etapas en ENTEROS u8: modificadores x / 255-x, operaciones con su saturacion, divisiones /255
 *    truncadas, escala x1/x2/x4 saturada, DOT3 entero por canal, buffer del combinador (la etapa 0 lee 0) y la
 *    peculiaridad de la etapa 0 (fuentes de color 1-2 "previo" -> fuente 3). Por construccion = tev_ref.
 *  - luz por fragmento (registros 0x140-0x1D9, LUTs 24x256 en una textura RG32F con (valor, diferencia)),
 *    salida u8 truncada como sw_lighting (con el +1e-3 de I/G para absorber el error de float).
 *  - alpha test, niebla (LUT 128), tijera (dentro/fuera), profundidad z/w-buffer con escala y offset.
 * El vertex shader de cada programa (.vert generado por tools/shader_glsl.py) se ENVUELVE: su main pasa a ser
 * pica_vmain y un main nuevo reparte los registros de salida o[] por semantica segun OUTMAP (0x04F-0x056 +
 * OUTMAP_MASK), con 1.0 en lo que no esta mapeado y el color abs+saturado por vertice (output_vertex.cpp).
 * Con luz, un geometry shader alinea el signo del cuaternion de normal de los 3 vertices con el del primero
 * (FlipQuaternionIfOpposite) antes de interpolar.
 */

/* interfaz VS -> (GS) -> FS: un bloque, asi el GS puede tener entrada y salida con el mismo nombre de bloque */
#define BLOQUE_V "V { vec4 color; vec4 tc01; vec4 tc2w; vec4 quat; vec4 view; }"

